-- ============================================================================
-- 祝日表。架電の関門が参照する。
--
-- ★ ライブラリではなく DB に持つ。祝日は法律で決まるもので、
--   改正（五輪のときの移動など）や新設がある。ライブラリだと
--   「祝日に架電してしまった」を直すのにデプロイが要る。
--   表なら運用で足せる。
--
-- ★ 国コードを持たせておく。海外拠点のテナントが増えたときに
--   テーブルを作り直さずに済む。
--
-- ★ 表が空なら「祝日なし」として扱う。fail open にしているのは、
--   祝日データの更新漏れで架電業務が全停止するほうが困るため。
--   その代わり、表が古いことを検知する運用チェックを別に置く。
-- ============================================================================

create table public_holidays (
  holiday_date date not null,
  country      text not null default 'JP',
  name         text not null,
  created_at   timestamptz not null default now(),
  primary key (country, holiday_date)
);

create index public_holidays_date_idx on public_holidays (holiday_date);

grant select on public_holidays to kaden_app;

